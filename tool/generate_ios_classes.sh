#!/bin/sh
# Regenerates ios/Classes and macos/Classes: one forwarding file per C source
# under src/.
#
# CocoaPods cannot reference files outside the pod's directory, so the iOS and
# macOS builds compile src/ through these. One file each, rather than a few that
# include many, because libsodium's sources reuse static function names across
# files; and named after the full path because FHSE has public/ and private/
# files with the same basename.
#
# Run after re-vendoring anything under src/vendor or adding a source to src/.
set -eu
cd "$(dirname "$0")/.."
for platform in ios macos; do
  mkdir -p "$platform/Classes"
  rm -f "$platform"/Classes/*.c
  find src -name '*.c' | LC_ALL=C sort | while read -r source; do
    name=$(printf '%s' "${source#src/}" | sed 's|/|__|g')
    printf '// Generated by tool/generate_ios_classes.sh from %s; do not edit.\n#include "../../%s"\n' \
      "$source" "$source" > "$platform/Classes/$name"
  done
  echo "$(ls "$platform"/Classes/*.c | wc -l | tr -d ' ') forwarding files in $platform/Classes"
done
